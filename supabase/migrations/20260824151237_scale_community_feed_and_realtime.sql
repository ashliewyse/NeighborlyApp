create or replace function public.get_my_inbox()
returns table (
  other_user_id uuid,
  last_message_id uuid,
  last_sender_id uuid,
  last_recipient_id uuid,
  last_message_body text,
  last_message_read_at timestamptz,
  last_message_created_at timestamptz,
  unread_count bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  with visible_messages as (
    select
      message.id,
      message.sender_id,
      message.recipient_id,
      message.body,
      message.read_at,
      message.created_at,
      case
        when message.sender_id = (select auth.uid()) then message.recipient_id
        else message.sender_id
      end as other_user_id
    from public.direct_messages message
    where message.sender_id = (select auth.uid())
       or message.recipient_id = (select auth.uid())
  ), ranked_messages as (
    select
      visible_message.*,
      row_number() over (
        partition by visible_message.other_user_id
        order by visible_message.created_at desc, visible_message.id desc
      ) as message_rank,
      count(*) filter (
        where visible_message.recipient_id = (select auth.uid())
          and visible_message.read_at is null
      ) over (partition by visible_message.other_user_id) as unread_count
    from visible_messages visible_message
  )
  select
    ranked_message.other_user_id,
    ranked_message.id,
    ranked_message.sender_id,
    ranked_message.recipient_id,
    ranked_message.body,
    ranked_message.read_at,
    ranked_message.created_at,
    ranked_message.unread_count
  from ranked_messages ranked_message
  where ranked_message.message_rank = 1
  order by ranked_message.created_at desc, ranked_message.id desc;
$$;

revoke all on function public.get_my_inbox() from public, anon;
grant execute on function public.get_my_inbox() to authenticated;

