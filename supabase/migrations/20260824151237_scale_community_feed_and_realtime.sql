create extension if not exists pg_trgm with schema extensions;

create table public.community_areas (
  id bigint generated by default as identity primary key,
  city text not null,
  neighborhood text,
  state_code text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint community_areas_city_length
    check (char_length(btrim(city)) between 1 and 120),
  constraint community_areas_neighborhood_length
    check (neighborhood is null or char_length(btrim(neighborhood)) between 1 and 120),
  constraint community_areas_state_code
    check (state_code is null or state_code ~ '^[A-Z]{2}$')
);

create unique index community_areas_unique_location_idx
  on public.community_areas (
    lower(btrim(city)),
    lower(coalesce(nullif(btrim(neighborhood), ''), ''))
  );

create index community_areas_directory_idx
  on public.community_areas (is_active, city, neighborhood);

