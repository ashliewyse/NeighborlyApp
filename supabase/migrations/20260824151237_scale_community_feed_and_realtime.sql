create or replace function private.broadcast_direct_message()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform realtime.send(
    jsonb_build_object(
      'id', new.id,
      'sender_id', new.sender_id,
      'recipient_id', new.recipient_id,
      'body', new.body,
      'read_at', new.read_at,
      'created_at', new.created_at
    ),
    'message_created',
    'user:' || new.recipient_id::text || ':inbox',
    true
  );
  return new;
end;
$$;

revoke all on function private.broadcast_direct_message() from public, anon, authenticated;

drop trigger if exists broadcast_direct_message on public.direct_messages;
create trigger broadcast_direct_message
  after insert on public.direct_messages
  for each row execute function private.broadcast_direct_message();

create or replace function private.broadcast_friendship_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  friendship_row public.friendships;
begin
  if tg_op = 'DELETE' then
    friendship_row := old;
  else
    friendship_row := new;
  end if;

  perform realtime.send(
    jsonb_build_object(
      'id', friendship_row.id,
      'requester_id', friendship_row.requester_id,
      'addressee_id', friendship_row.addressee_id,
      'status', friendship_row.status,
      'operation', tg_op
    ),
    'friendship_changed',
    'user:' || friendship_row.requester_id::text || ':inbox',
    true
  );

  perform realtime.send(
    jsonb_build_object(
      'id', friendship_row.id,
      'requester_id', friendship_row.requester_id,
      'addressee_id', friendship_row.addressee_id,
      'status', friendship_row.status,
      'operation', tg_op
    ),
    'friendship_changed',
    'user:' || friendship_row.addressee_id::text || ':inbox',
    true
  );

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

revoke all on function private.broadcast_friendship_change() from public, anon, authenticated;

drop trigger if exists broadcast_friendship_change on public.friendships;
create trigger broadcast_friendship_change
  after insert or update or delete on public.friendships
  for each row execute function private.broadcast_friendship_change();
