create or replace view public.community_groups_directory
with (security_invoker = true)
as
select
  community_group.id,
  community_group.name,
  community_group.description,
  community_group.emoji,
  community_group.city,
  community_group.neighborhood,
  community_group.created_by,
  community_group.is_active,
  community_group.created_at,
  count(group_member.user_id)::bigint as member_count
from public.community_groups community_group
left join public.community_group_members group_member
  on group_member.group_id = community_group.id
group by community_group.id;

revoke all on public.community_groups_directory from anon, authenticated;
grant select on public.community_groups_directory to authenticated;

create or replace function public.create_community_group(
  group_name text,
  group_description text,
  group_emoji text,
  group_city text,
  group_neighborhood text default null
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  created_group_id uuid;
begin
  if not private.has_site_access() or (select auth.uid()) is null then
    raise exception 'Approved membership is required';
  end if;

  insert into public.community_groups (
    name,
    description,
    emoji,
    city,
    neighborhood,
    created_by
  )
  values (
    btrim(group_name),
    btrim(group_description),
    coalesce(nullif(btrim(group_emoji), ''), '🏘️'),
    btrim(group_city),
    nullif(btrim(group_neighborhood), ''),
    (select auth.uid())
  )
  returning id into created_group_id;

  insert into public.community_group_members (group_id, user_id)
  values (created_group_id, (select auth.uid()));

  return created_group_id;
end;
$$;

revoke all on function public.create_community_group(text, text, text, text, text) from public, anon;
grant execute on function public.create_community_group(text, text, text, text, text) to authenticated;

