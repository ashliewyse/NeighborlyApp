create or replace function private.sync_profile_community_area()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if nullif(btrim(new.city), '') is not null then
    insert into public.community_areas (city, neighborhood)
    values (btrim(new.city), null)
    on conflict do nothing;

    if nullif(btrim(new.neighborhood), '') is not null then
      insert into public.community_areas (city, neighborhood)
      values (btrim(new.city), btrim(new.neighborhood))
      on conflict do nothing;
    end if;
  end if;
  return new;
end;
$$;

revoke all on function private.sync_profile_community_area() from public, anon, authenticated;

drop trigger if exists sync_profile_community_area on public.profiles;
create trigger sync_profile_community_area
  after insert or update of city, neighborhood on public.profiles
  for each row execute function private.sync_profile_community_area();

create table public.community_groups (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text not null,
  emoji text not null default '🏘️',
  city text not null,
  neighborhood text,
  created_by uuid references public.profiles (id) on delete set null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint community_groups_name_length
    check (char_length(btrim(name)) between 3 and 80),
  constraint community_groups_description_length
    check (char_length(btrim(description)) between 5 and 300),
  constraint community_groups_emoji_length
    check (char_length(emoji) between 1 and 12),
  constraint community_groups_city_length
    check (char_length(btrim(city)) between 1 and 120),
  constraint community_groups_neighborhood_length
    check (neighborhood is null or char_length(btrim(neighborhood)) between 1 and 120)
);

